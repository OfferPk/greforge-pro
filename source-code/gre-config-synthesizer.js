/**
 * GREForge Pro - Multi-Platform GRE & Tunnel Configuration Synthesizer
 * Generates production-ready configurations for:
 * - Cisco IOS-XE (DMVPN Phase 3 mGRE + IPsec + BFD)
 * - Linux Kernel `ip link` & `iptables` (GRE / GRE-in-UDP)
 * - Juniper Junos (`gr-` interface)
 * - Cloudflare Magic Transit (Anycast BGP + GRE Endpoint)
 * - Prometheus Tunnel Health & Flapping Alerting Rules
 */

(function (root, factory) {
  if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.GreConfigSynthesizer = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function generateCiscoConfig(params) {
    const tunnelId = params.tunnelId || 1;
    const localIp = params.localIp || '198.51.100.1';
    const remoteIp = params.remoteIp || '203.0.113.2';
    const overlayIp = params.overlayIp || '10.255.255.1';
    const keyVal = params.keyVal || 10001;
    const isMultipoint = !!params.isMultipoint;

    return `! ====================================================================
! Cisco IOS-XE Enterprise GRE / DMVPN Phase 3 Configuration
! Standards: RFC 2784 GRE / RFC 2890 Key / RFC 5880 BFD
! Generated by GREForge Pro v1.0.0
! ====================================================================

! 1. IPsec Profile for Wire-Speed Overlay Encryption
crypto ipsec transform-set TS_GRE_IPSEC esp-gcm 256
 mode transport
!
crypto ipsec profile IPSEC_PROF_GRE
 set transform-set TS_GRE_IPSEC
 set pfs group20
!
! 2. Route-Map Filter to Prevent Recursive Routing Loops (TUNRECURSEREG)
ip access-list standard ACL_UNDERLAY_ENDPOINTS
 permit host ${localIp}
 permit host ${remoteIp}
!
route-map RM_PREVENT_RECURSION deny 10
 match ip address ACL_UNDERLAY_ENDPOINTS
!
route-map RM_PREVENT_RECURSION permit 20
!
! 3. Dedicated Tunnel Interface with BFD & MSS Clamping
interface Tunnel${tunnelId}
 description Enterprise Zero-Trust GRE Overlay
 ip address ${overlayIp} 255.255.255.0
 ip mtu 1400
 ip tcp adjust-mss 1360
 ${isMultipoint ? 'tunnel mode gre multipoint' : 'tunnel mode gre ip'}
 tunnel source ${localIp}
 ${isMultipoint ? '! Remote endpoints dynamically resolved via NHRP' : `tunnel destination ${remoteIp}`}
 tunnel key ${keyVal}
 tunnel protection ipsec profile IPSEC_PROF_GRE
 !
 ! Hardware-Accelerated BFD Health Tracking (Sub-Second Failover)
 bfd interval 300 min_rx 300 multiplier 3
 !
 ! Ingress Reverse Path Forwarding (uRPF Anti-Spoofing)
 ip verify unicast source reachable-via rx
!
`;
  }

  function generateLinuxConfig(params) {
    const dev = params.dev || 'gre0';
    const localIp = params.localIp || '198.51.100.1';
    const remoteIp = params.remoteIp || '203.0.113.2';
    const overlayIp = params.overlayIp || '10.255.255.1';
    const keyVal = params.keyVal || 10001;
    const isGreInUdp = !!params.isGreInUdp;

    if (isGreInUdp) {
      return `### ====================================================================
### Linux Kernel RFC 8086 GRE-in-UDP Tunnel Script
### Subsystem: iproute2 + fou (Foo-over-UDP) Port 4754
### Generated by GREForge Pro v1.0.0
### ====================================================================

# 1. Load FOU Kernel Module
modprobe fou

# 2. Add Local Receiving UDP Port 4754 for GRE-in-UDP
ip fou add port 4754 ipproto 47

# 3. Create GRE-in-UDP Virtual Interface
ip link add name ${dev} type gre \\
  local ${localIp} \\
  remote ${remoteIp} \\
  key ${keyVal} \\
  encap fou \\
  encap-sport auto \\
  encap-dport 4754

# 4. Assign Overlay IP Address and Safe MTU
ip addr add ${overlayIp}/24 dev ${dev}
ip link set dev ${dev} mtu 1464 up

# 5. Enforce TCP MSS Clamping via iptables
iptables -t mangle -A FORWARD -p tcp --tcp-flags SYN,RST SYN -o ${dev} -j TCPMSS --clamp-mss-to-pmtu
`;
    }

    return `### ====================================================================
### Linux Kernel RFC 2784 / RFC 2890 GRE Tunnel Script
### Subsystem: iproute2 + iptables MSS Clamping
### Generated by GREForge Pro v1.0.0
### ====================================================================

# 1. Create Point-to-Point GRE Tunnel with 32-bit Key
ip link add name ${dev} type gre \\
  local ${localIp} \\
  remote ${remoteIp} \\
  key ${keyVal} \\
  ttl 64

# 2. Assign Overlay IP and Configure MTU
ip addr add ${overlayIp}/24 dev ${dev}
ip link set dev ${dev} mtu 1476 up

# 3. Enforce Ingress Strict uRPF Anti-Spoofing
sysctl -w net.ipv4.conf.${dev}.rp_filter=1

# 4. Enforce TCP MSS Clamping to prevent PMTU blackholes
iptables -t mangle -A FORWARD -p tcp --tcp-flags SYN,RST SYN -o ${dev} -j TCPMSS --set-mss 1360
`;
  }

  function generateJunosConfig(params) {
    const localIp = params.localIp || '198.51.100.1';
    const remoteIp = params.remoteIp || '203.0.113.2';
    const overlayIp = params.overlayIp || '10.255.255.1';
    const keyVal = params.keyVal || 10001;

    return `# ====================================================================
# Juniper Junos GRE Tunnel Configuration (gr- interface)
# Standards: RFC 2784 GRE / RFC 2890 Key
# Generated by GREForge Pro v1.0.0
# ====================================================================

set interfaces gr-0/0/0 unit 0 description "Zero-Trust Enterprise GRE Tunnel"
set interfaces gr-0/0/0 unit 0 tunnel source ${localIp}
set interfaces gr-0/0/0 unit 0 tunnel destination ${remoteIp}
set interfaces gr-0/0/0 unit 0 tunnel key ${keyVal}
set interfaces gr-0/0/0 unit 0 family inet mtu 1476
set interfaces gr-0/0/0 unit 0 family inet address ${overlayIp}/24

# Enforce TCP MSS Clamping in Forwarding Options
set forwarding-options tcp-mss all-tcp mss 1360

# BFD Sub-Second Session Monitoring
set protocols bfd-liveness-detection interface gr-0/0/0.0 minimum-interval 300
set protocols bfd-liveness-detection interface gr-0/0/0.0 multiplier 3
`;
  }

  function generateCloudflareConfig(params) {
    const localIp = params.localIp || '198.51.100.1';
    const cfAnycastIp = params.remoteIp || '162.159.64.1';
    const overlayIp = params.overlayIp || '10.255.255.1';

    return `// ====================================================================
// Cloudflare Magic Transit Anycast GRE Tunnel (Terraform HCL)
// Standards: RFC 2784 GRE with Anycast BGP Routing
// Generated by GREForge Pro v1.0.0
// ====================================================================

resource "cloudflare_magic_transit_gre_tunnel" "customer_gre_tunnel" {
  account_id           = var.cloudflare_account_id
  name                 = "primary_site_magic_transit_gre"
  customer_gre_endpoint = "${localIp}"
  cloudflare_gre_endpoint = "${cfAnycastIp}"
  interface_address    = "${overlayIp}/31"
  description          = "Anycast DDoS Protected GRE Ingress"
  mtu                  = 1476
  ttl                  = 64
  health_check {
    type      = "request"
    direction = "bidirectional"
    rate      = "mid"
  }
}

resource "cloudflare_magic_transit_route" "enterprise_subnet" {
  account_id = var.cloudflare_account_id
  network    = "192.168.10.0/24"
  nexthop    = "${overlayIp}"
  priority   = 100
  scope {
    gre_endpoints = [cloudflare_magic_transit_gre_tunnel.customer_gre_tunnel.id]
  }
}
`;
  }

  function generatePrometheusConfig() {
    return `### ====================================================================
### Prometheus Alerting Rules for GRE & Tunnel Infrastructure
### Generated by GREForge Pro v1.0.0
### ====================================================================

groups:
  - name: gre_tunnel_alerts
    rules:
      - alert: GRETunnelInterfaceDown
        expr: ifOperStatus{ifType="tunnel", ifDescr=~".*gre.*"} != 1
        for: 30s
        labels:
          severity: critical
          category: overlay_down
        annotations:
          summary: "GRE Tunnel Interface Down on {{ $labels.instance }}"
          description: "Interface {{ $labels.ifDescr }} is down. Check underlay transport or BFD liveness."

      - alert: GRETunnelRecursiveRoutingLoop
        expr: rate(cisco_tunnel_recursive_routing_drops_total[1m]) > 0
        for: 15s
        labels:
          severity: critical
          category: routing_loop
        annotations:
          summary: "Recursive Routing Loop Detected on GRE Tunnel"
          description: "Router {{ $labels.instance }} detected TUNRECURSEREG. Tunnel destination IP is being advertised into overlay."

      - alert: GREPathMtuBlackholeRisk
        expr: rate(node_netstat_IcmpMsg_InType3_Code4[1m]) > 5
        for: 2m
        labels:
          severity: warning
          category: pmtu_blackhole
        annotations:
          summary: "ICMP Fragmentation Needed Drops Detected"
          description: "GRE packets exceeding underlay MTU. Verify TCP MSS clamping (adjust-mss 1360) or enable Jumbo frames."
`;
  }

  return {
    generateCiscoConfig,
    generateLinuxConfig,
    generateJunosConfig,
    generateCloudflareConfig,
    generatePrometheusConfig
  };
}));
